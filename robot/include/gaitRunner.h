/*
  gaitRunner.h - Autonomous playback of precomputed gait trajectory tables
  (see gaitTables.h, generated by python-tools/q8bot/export_gait_tables.py).

  Lets the robot walk a gait/direction on its own once told to (via the
  GAIT_RUN command, see protocol.h), instead of needing one MOVE frame
  streamed from the host per tick. A raw MOVE command always stops this
  first (see q8Dynamixel::parseFrame()'s MOVE case) - the host can still
  drive the robot directly at any time.
*/
#ifndef gaitRunner_h
#define gaitRunner_h

#include <Arduino.h>
#include "q8Dynamixel.h"

class GaitRunner {
  public:
    GaitRunner(q8Dynamixel& q8);

    // Starts (or switches direction within) the given gait. Phase is only
    // reset when gaitId actually changes - a direction-only change carries
    // the phase over, matching GaitManager.start_movement()'s behavior in
    // python-tools (all direction tables for one gait share a frame count,
    // so this stays continuous, no stutter on turning).
    void start(uint8_t gaitId, uint8_t directionId);

    // Stops autonomous playback. Does not move the legs anywhere - caller
    // (e.g. a subsequent MOVE or moveToIdle()) is responsible for that.
    void stop();

    // Advances one frame and writes it out. No-op if not active. Call this
    // periodically (e.g. every 5ms) from a dedicated task.
    void tick();

    bool isActive() const;

  private:
    q8Dynamixel& _q8;
    bool _active = false;
    uint8_t _gaitId = 0;
    uint8_t _directionId = 0;
    uint16_t _phaseIndex = 0;
};

#endif
